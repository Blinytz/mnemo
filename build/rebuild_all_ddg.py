"""
Reconstruction complète de toutes les images full/ via DuckDuckGo Images.
Stratégie : query optimisée par liste + téléchargement de la meilleure image (max résolution).
Scoring automatique sur la qualité (résolution, taille fichier).
"""
import sys, pathlib, requests, time, csv
sys.stdout.reconfigure(encoding='utf-8', line_buffering=True)
from duckduckgo_search import DDGS
from PIL import Image
from io import BytesIO

BASE = pathlib.Path(r'C:\Users\flxjr\OneDrive\Bureau\memo-app')
FULL = BASE / 'full'
HEADERS = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120'}
SKIP = {'pays', 'departements', 'etats_usa', 'elements', 'periodes_geologiques',
        'vocabulaire_precis', 'phrasal_verbs', 'os'}

LOG = open(BASE / 'build' / 'ddg_results.csv', 'w', newline='', encoding='utf-8')
csv_writer = csv.writer(LOG)
csv_writer.writerow(['folder','num','query','source_url','width','height','kb','score_qualite','note'])
FAIL_LOG = open(BASE / 'build' / 'ddg_fails.txt', 'w', encoding='utf-8')

ddgs = DDGS()

def search_and_download(folder, num, query, min_px=800):
    """Cherche sur DDG, télécharge la meilleure image ≥ min_px."""
    try:
        results = list(ddgs.images(query, max_results=10, size='Large'))
        time.sleep(0.8)
    except Exception as e:
        try:
            time.sleep(5)
            results = list(ddgs.images(query, max_results=6))
            time.sleep(0.8)
        except Exception as e2:
            return None, f'DDG error: {e2}'

    if not results:
        return None, 'no results'

    # Trier par résolution décroissante
    results.sort(key=lambda r: r.get('width', 0) * r.get('height', 0), reverse=True)

    for r in results[:6]:
        url = r.get('image', '')
        if not url:
            continue
        try:
            resp = requests.get(url, headers=HEADERS, timeout=12, stream=True)
            if resp.status_code != 200:
                continue
            content = resp.content
            if len(content) < 5000:
                continue
            img = Image.open(BytesIO(content)).convert('RGB')
            w, h = img.size
            if max(w, h) < 400:
                continue
            # Sauvegarder
            img.thumbnail((1200, 1200), Image.LANCZOS)
            for old in (FULL / folder).glob(f'{num}.*'):
                old.unlink()
            out = FULL / folder / f'{num}.jpg'
            img.save(out, 'JPEG', quality=88, optimize=True)
            kb = out.stat().st_size // 1024
            fw, fh = img.size
            # Score qualité (0-10)
            score = min(10, int(max(fw, fh) / 120))
            return (url, w, h, fw, fh, kb, score), None
        except Exception:
            continue

    return None, f'all downloads failed for: {query}'

def process_list(folder, entries_with_queries):
    """entries_with_queries : dict {num: (title, query)}"""
    fp = FULL / folder
    fp.mkdir(parents=True, exist_ok=True)
    ok = fail = 0
    print(f'\n=== {folder} ({len(entries_with_queries)}) ===')

    for num, (title, query) in sorted(entries_with_queries.items()):
        result, err = search_and_download(folder, num, query)
        if result:
            url, w0, h0, fw, fh, kb, sq = result
            note = '✓' if sq >= 7 else ('~' if sq >= 5 else '⚠')
            print(f'  #{num} {note} {fw}x{fh} {kb}KB — {title}')
            csv_writer.writerow([folder, num, query, url, fw, fh, kb, sq, note])
            LOG.flush()
            ok += 1
        else:
            print(f'  #{num} ECHEC — {title} ({err})')
            FAIL_LOG.write(f'{folder}\t{num}\t{title}\t{query}\t{err}\n')
            FAIL_LOG.flush()
            fail += 1

    print(f'  → {ok} OK, {fail} échecs')
    return ok, fail


